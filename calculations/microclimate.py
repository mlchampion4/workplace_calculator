def score_temperature(t, period):
    """t - °C, period: 'cold' или 'warm'."""
    if period == 'warm':
        opt_lo, opt_hi, adm_lo, adm_hi = 22, 24, 20, 28
    else:
        opt_lo, opt_hi, adm_lo, adm_hi = 21, 23, 20, 24
    if opt_lo <= t <= opt_hi:
        return 0, "Оптимум", ""
    if adm_lo <= t <= adm_hi:
        return 1, "Допустимо", "Скорректировать работу кондиционера/отопления."
    if t < adm_lo:
        return 2, "Холодно (вредно)", "Утеплить помещение, добавить обогреватель, тёплую одежду."
    return 2, "Жарко (вредно)", "Кондиционер, проветривание, питьевой режим, перерывы."

def score_humidity(h):
    if 40 <= h <= 60:
        return 0, "Оптимум", ""
    if 30 <= h < 40 or 60 < h <= 70:
        return 1, "Допустимо", "Увлажнитель/осушитель воздуха."
    return 2, "Вредно (<30% или >70%)", "Установить увлажнитель (зимой) или осушитель/вентиляцию (летом)."

def score_air_speed(v):
    if v <= 0.1:
        return 0, "Оптимум", ""
    if v <= 0.2:
        return 1, "Допустимо", "Снизить скорость потока (направить диффузор)."
    return 2, "Сквозняк (вредно)", "Перенаправить воздушный поток, исключить сквозняки, переместить рабочее место."

def score_surface_temp(delta):
    """delta = t_воздуха - t_поверхности"""
    if delta <= 2:
        return 0, "Оптимум", ""
    if delta <= 4:
        return 1, "Допустимо", "Утеплить наружные стены/окна."
    return 2, "Вредно", "Утепление ограждающих конструкций, радиаторные экраны."