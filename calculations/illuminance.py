def score_illuminance(e):
    if 400 <= e <= 500:
        return 0, "Оптимум", ""
    if 300 <= e < 400 or 500 < e <= 600:
        return 1, "Допустимо", "Отрегулировать яркость/добавить местный светильник."
    return 2, "Вредно (вне 300-500 лк)", "Организовать комбинированное освещение (общее + местное), LED 400-500 лк на рабочей поверхности."

def score_pulsation(k):
    if k <= 5:
        return 0, "Оптимум", ""
    if k <= 10:
        return 1, "Допустимо", "Заменить драйверы/лампы на качественные LED."
    return 2, "Вредно (>10%)", "Срочно заменить светильники с высоким коэффициентом пульсации."

def score_brightness(b):
    if 100 <= b <= 200:
        return 0, "Оптимум", ""
    if 80 <= b < 100 or 200 < b <= 250:
        return 1, "Допустимо", "Настроить яркость монитора."
    return 2, "Вредно", "Настроить яркость экрана до 100-200 кд/м², избегать работы в темноте."

def score_contrast(c):
    if c >= 3:
        return 0, "Оптимум", ""
    if c >= 2:
        return 1, "Допустимо", "Повысить контраст текста/фона."
    return 2, "Вредно", "Увеличить контраст (тёмный текст на светлом фоне), настроить тему IDE."

def score_unevenness(r):
    if r <= 3:
        return 0, "Оптимум", ""
    if r <= 5:
        return 1, "Допустимо", "Выровнять освещение: добавить светильники, убрать тени."
    return 2, "Вредно", "Перепланировать освещение, исключить резкие тени."

def score_keo(k):
    if k >= 1.0:
        return 0, "Оптимум", ""
    if k >= 0.5:
        return 1, "Допустимо", "Чаще проветривать/мыть окна, увеличить площадь остекления."
    return 2, "Вредно", "Переместить рабочее место ближе к окну, добавить общее освещение."