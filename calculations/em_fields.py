def score_distance(d):
    if d >= 70: return 0, "Оптимум", ""
    if d >= 50: return 1, "Допустимо", "Отодвинуть монитор на 60-70 см."
    return 2, "Вредно", "Установить монитор на расстоянии 50-70 см, верх экрана на уровне глаз."