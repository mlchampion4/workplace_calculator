def score_noise(n):
    if n <= 50: return 0, "Оптимум", ""
    if n <= 60: return 1, "Допустимо", "Шумоподавление, ковролин, звукоизоляция."
    if n <= 80: return 2, "Вредно", "Средства индивидуальной защиты слуха, звукоизоляция, перенос оборудования."
    return 3, "Критично (>80 дБА)", "Немедленно снизить уровень шума, СИЗ слуха, медосмотр."