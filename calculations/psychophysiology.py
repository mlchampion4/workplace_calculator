def score_continuous_minutes(m):
    if m <= 45: return 0, "Оптимум", ""
    if m <= 60: return 1, "Допустимо", "Делать перерывы 10-15 мин каждый час."
    return 2, "Вредно", "Внедрить регламентированные перерывы каждые 45-60 мин, гимнастика для глаз."

def score_screen_hours(h):
    if h <= 4: return 0, "Оптимум", ""
    if h <= 6: return 1, "Допустимо", "Соблюдать режим перерывов, гимнастика для глаз."
    return 2, "Вредно", "Сократить время за экраном, перераспределить задачи, перерывы каждые 45 мин."

def score_monotony(m):
    """m: 1-5, выше — хуже."""
    if m <= 2: return 0, "Оптимум", ""
    if m <= 3: return 1, "Допустимо", "Чередовать задачи, добавить двигательную активность."
    return 2, "Вредно", "Диверсифицировать задачи, ротация, микроперерывы."

def score_overtime_hours(y):
    if y <= 120: return 0, "Оптимум", ""
    if y <= 180: return 1, "Допустимо", "Сократить переработки, планирование задач."
    return 2, "Вредно", "Пересмотреть нагрузку, соблюдать ТК РБ (≤120 ч/год)."

def score_overtime_week(w):
    if w <= 10: return 0, "Оптимум", ""
    if w <= 16: return 1, "Допустимо", "Контроль переработок."
    return 2, "Вредно (>10 ч/нед)", "Снизить недельную переработку, обсудить с руководителем."
